-- ═══════════════════════════════════════════════════════════════════════════
-- وصل | أقلُّ صلاحيةٍ تكفي
-- ═══════════════════════════════════════════════════════════════════════════
--
-- Supabase يمنح `anon` و`authenticated` **كلَّ شيءٍ على كل جدول** في `public`
-- افتراضًا، ويتّكل على RLS وحدها في المنع. وهذا يعمل — ما دامت كل سياسةٍ
-- صحيحة، وما دام كل جدولٍ جديدٍ يُكتب له سياسة.
--
-- **وهذا اتّكالٌ على طبقةٍ واحدة.** فسياسةٌ تُكتب غدًا بخطأٍ صغير، أو جدولٌ
-- يُنشأ وتُنسى سياستُه، يصير عندها مفتوحًا **للكتابة من كل حامل مفتاحٍ منشور**
-- — وهو مفتاحٌ في كل حزمةٍ على كل هاتف.
--
-- فتُسحب الكتابة من الزائر سحبًا صريحًا. والقراءة تبقى حيث مُنحت عمدًا
-- (الكتالوج والأسعار يراهما من لم يسجّل بعد). وتبقى RLS الحارسَ الأوّل —
-- وهذا حارسٌ ثانٍ خلفها، لا بديلٌ عنها.
--
-- **ولماذا لم يُكتشف هذا إلا الآن**: محاكاةُ الاختبار المحلّيّ لم تكن تمنح
-- تلك الصلاحيات الافتراضية، فكان فحصُ الصلاحيات يمرّ على قاعدةٍ لا صلاحية
-- فيها أصلًا — يمرّ بلا أن يفحص شيئًا. أُصلحت المحاكاة أوّلًا، ففشل الفحص،
-- فكُتبت هذه المهاجرة.

set search_path = public, extensions;

-- ─────────────────────────────────────────────────────────────────────────
-- ١) الزائر يقرأ ولا يكتب
-- ─────────────────────────────────────────────────────────────────────────
revoke insert, update, delete, truncate on all tables in schema public from anon;

-- ولا يكتب في جدولٍ يُنشأ غدًا كذلك.
alter default privileges in schema public
  revoke insert, update, delete, truncate on tables from anon;

-- ─────────────────────────────────────────────────────────────────────────
-- ٢) جداولٌ لا تُكتب من حزمةٍ إطلاقًا
-- ─────────────────────────────────────────────────────────────────────────
-- هذه يكتبها الخادمُ أو المحفّزات وحدها (ودوالُّ `security definer` تعمل
-- بصلاحية مالكها فلا يمسّها هذا السحب). ومنعُها على مستوى الصلاحية يعني أن
-- خطأً في سياسةٍ مستقبلًا لا يفتحها.
do $$
declare t text;
begin
  foreach t in array array[
    -- آلةُ الحالات: بياناتٌ مرجعيّة تُقرأ ولا تُعدَّل من تطبيق. ومن يكتب فيها
    -- يخترع لنفسه انتقالًا مسموحًا.
    'order_transitions',
    -- رمز التسليم: لا يُقرأ ولا يُكتب — يُولَّد ويُقارَن في القاعدة.
    'order_delivery_codes',
    -- الوارد الخام من بوّابة الدفع.
    'payment_webhook_events',
    -- حركاتُ النقاط: تُكسب بمحفّز وتُصرف بدالّة. وكتابتُها يدويًّا طبعُ مال.
    'loyalty_transactions'
  ] loop
    execute format(
      'revoke insert, update, delete, truncate on public.%I from anon, authenticated', t);
  end loop;
end $$;

-- ─────────────────────────────────────────────────────────────────────────
-- ٣) ولا تُنشأ دوالُّ مكشوفةً افتراضًا
-- ─────────────────────────────────────────────────────────────────────────
-- كلُّ دالّةٍ تُنشأ تُمنح EXECUTE لـPUBLIC — وهو ما جعل دوالَّ المحفّزات تظهر
-- على `/rest/v1/rpc/`. المهاجراتُ تسحبها واحدةً واحدة، وهذا يمنعها من البدء.
alter default privileges in schema public
  revoke execute on functions from public;

comment on schema public is
  'الزائر يقرأ ولا يكتب: سُحبت صلاحيات الكتابة صراحةً، وRLS حارسٌ أوّل لا وحيد.';
